// Package blockdevice extends the openstack_compute_instance_v2 Terraform
// schema so that block devices can reference an image by name.
//
// The upstream Terraform provider only accepts an image UUID in
// block_device.uuid (the top-level image_name is ignored for boot-from-volume).
// That makes it impossible to use the same manifest on clusters that do not
// have a matching ImageV2 object or the same image UUID.
//
// The extension is done fully on the Crossplane provider side: a new
// block_device.image_name attribute is added to the schema and resolved to
// block_device.uuid right before the upstream create function is called.
// On refresh the attribute is populated back from the image the boot volume
// was created from, so changing the name in the spec is detected as drift and
// forces a new server.
package blockdevice

import (
	"context"
	"fmt"
	"log"
	"strconv"
	"strings"

	"github.com/crossplane/upjet/v2/pkg/config"
	"github.com/gophercloud/gophercloud/v2/openstack/image/v2/images"
	imagesutils "github.com/gophercloud/utils/v2/openstack/image/v2/images"
	"github.com/hashicorp/go-cty/cty"
	"github.com/hashicorp/terraform-plugin-sdk/v2/diag"
	"github.com/hashicorp/terraform-plugin-sdk/v2/helper/schema"
	"github.com/pkg/errors"
	"github.com/terraform-provider-openstack/terraform-provider-openstack/v3/openstack"
)

const (
	blockDeviceField = "block_device"
	imageNameField   = "image_name"
	uuidField        = "uuid"
	sourceTypeField  = "source_type"

	sourceTypeImage = "image"
)

// imageResolver resolves an image name to an image ID.
type imageResolver func(ctx context.Context, d *schema.ResourceData, meta any, name string) (string, error)

// imageNamer resolves an image ID to an image name.
type imageNamer func(ctx context.Context, d *schema.ResourceData, meta any, id string) (string, error)

// ConfigureImageName adds block_device.image_name to the given resource and
// makes the create function resolve it to block_device.uuid.
func ConfigureImageName(r *config.Resource) {
	if r.TerraformResource == nil {
		return
	}
	extendResource(r.TerraformResource, resolveImageIDByName, resolveImageNameByID)

	// image_name is populated from the observed image on refresh. Late
	// initialization must not copy it into spec next to uuid.
	//
	// uuid is intentionally NOT in IgnoredFields: upjet must late-initialize it
	// for volume/snapshot devices that never use imageName. For image-backed
	// devices with imageName in initProvider, late-init will copy the resolved
	// UUID into forProvider, but wrapCreate handles the recreation case by
	// resolving imageName fresh and overwriting any stale UUID.
	r.LateInitializer.IgnoredFields = append(r.LateInitializer.IgnoredFields, blockDeviceField+"."+imageNameField)
}

func extendResource(res *schema.Resource, resolve imageResolver, name imageNamer) {
	bd, ok := res.Schema[blockDeviceField]
	if !ok {
		return
	}
	bdRes, ok := bd.Elem.(*schema.Resource)
	if !ok {
		return
	}

	bdRes.Schema[imageNameField] = &schema.Schema{
		Type:     schema.TypeString,
		Optional: true,
		ForceNew: true,
		// provider-metadata.yaml is regenerated by the scraper and has no entry
		// for this attribute, so the description has to live here. Note that
		// upjet prepends the top-level image_name docs as a fallback.
		Description: "In a block device the name is resolved to the image ID before the server " +
			"is created, so the image does not need to exist as a managed resource. " +
			"Can only be used with source_type \"image\" and conflicts with uuid. " +
			"Supports boot-from-volume with destination_type \"volume\". " +
			"For destination_type \"local\", a top-level image_id or image_name is also required; " +
			"this block-device field alone is not sufficient for local-disk boot. " +
			"Changing this creates a new server.",
		DiffSuppressFunc: suppressImageName,
	}
	if uuid, ok := bdRes.Schema[uuidField]; ok {
		uuid.DiffSuppressFunc = suppressUUID
	}

	// CreateContext is nil when the schema is built from the JSON schema for
	// code generation; there is nothing to wrap in that case.
	if create := res.CreateContext; create != nil {
		res.CreateContext = wrapCreate(create, resolve)
	}
	if read := res.ReadContext; read != nil {
		res.ReadContext = wrapRead(read, name)
	}
}

// suppressImageName hides image_name diffs that cannot be compared:
//   - the config does not set image_name (uuid is used instead), while the
//     state holds the observed image name;
//   - the existing server has no observed image name (e.g. the image was
//     deleted or the lookup failed), so there is nothing to compare with.
//
// Otherwise a changed name is a real diff and forces a new server.
func suppressImageName(_, oldValue, newValue string, d *schema.ResourceData) bool {
	if newValue == "" {
		return true
	}

	return d.Id() != "" && oldValue == ""
}

// suppressUUID hides uuid diffs when the config sets image_name. uuid is then
// derived from the name: the state holds the resolved image ID, while the spec
// may hold nothing or a stale ID copied by late initialization before the image
// was replaced under the same name. Drift is detected on image_name instead.
func suppressUUID(k, _, _ string, d *schema.ResourceData) bool {
	return configImageName(k, d) != ""
}

// configImageName returns image_name of the block device owning key k as set
// in the configuration. ResourceData.Get falls back to the state for
// attributes missing from the configuration, so the raw config is read.
func configImageName(k string, d *schema.ResourceData) string {
	parts := strings.Split(k, ".")
	if len(parts) != 3 {
		return ""
	}
	i, err := strconv.Atoi(parts[1])
	if err != nil {
		return ""
	}
	v, diags := d.GetRawConfigAt(cty.GetAttrPath(blockDeviceField).IndexInt(i).GetAttr(imageNameField))
	if diags.HasError() || !v.IsKnown() || v.IsNull() || !v.Type().Equals(cty.String) {
		return ""
	}

	return v.AsString()
}

func wrapCreate(create schema.CreateContextFunc, resolve imageResolver) schema.CreateContextFunc {
	return func(ctx context.Context, d *schema.ResourceData, meta any) diag.Diagnostics {
		if err := resolveImageNames(ctx, d, meta, resolve); err != nil {
			return diag.FromErr(err)
		}

		return create(ctx, d, meta)
	}
}

// resolveImageNames replaces image_name with the resolved uuid in every block
// device that sets it.
func resolveImageNames(ctx context.Context, d *schema.ResourceData, meta any, resolve imageResolver) error {
	devices, ok := d.Get(blockDeviceField).([]any)
	if !ok {
		return nil
	}

	changed := false
	for i, raw := range devices {
		bd, ok := raw.(map[string]any)
		if !ok {
			continue
		}
		name, _ := bd[imageNameField].(string)
		if name == "" {
			continue
		}
		if uuid, _ := bd[uuidField].(string); uuid != "" {
			// uuid may have been late-initialized from the observed TF state
			// while imageName is set in initProvider. image_name takes
			// precedence; the stale uuid is cleared so the upstream create does
			// not receive conflicting inputs.
			log.Printf("[DEBUG] block_device.%d: image_name set together with uuid %q"+
				" (likely late-initialized); clearing uuid and using image_name", i, uuid)
			delete(bd, uuidField)
		}
		if st, _ := bd[sourceTypeField].(string); st != sourceTypeImage {
			return fmt.Errorf("block_device.%d: image_name requires source_type %q, got %q", i, sourceTypeImage, st)
		}

		id, err := resolve(ctx, d, meta, name)
		if err != nil {
			return errors.Wrapf(err, "block_device.%d: cannot resolve image_name %q", i, name)
		}
		bd[uuidField] = id
		changed = true
	}

	if !changed {
		return nil
	}

	return errors.Wrap(d.Set(blockDeviceField, devices), "cannot set resolved block_device")
}

func resolveImageIDByName(ctx context.Context, d *schema.ResourceData, meta any, name string) (string, error) {
	cfg, ok := meta.(*openstack.Config)
	if !ok {
		return "", errors.Errorf("unexpected provider meta type %T", meta)
	}
	client, err := cfg.ImageV2Client(ctx, openstack.GetRegion(d, cfg))
	if err != nil {
		return "", errors.Wrap(err, "cannot create OpenStack image client")
	}

	return imagesutils.IDFromName(ctx, client, name)
}

func wrapRead(read schema.ReadContextFunc, name imageNamer) schema.ReadContextFunc {
	return func(ctx context.Context, d *schema.ResourceData, meta any) diag.Diagnostics {
		diags := read(ctx, d, meta)
		if diags.HasError() || d.Id() == "" {
			return diags
		}
		populateImageNames(ctx, d, meta, name)

		return diags
	}
}

// populateImageNames sets image_name of image-backed block devices to the
// current name of the image referenced by uuid. The upstream read function
// rebuilds block_device without it. Lookup failures are ignored and leave the
// previous value untouched, so a deleted or inaccessible image never causes a
// diff.
func populateImageNames(ctx context.Context, d *schema.ResourceData, meta any, name imageNamer) {
	devices, ok := d.Get(blockDeviceField).([]any)
	if !ok {
		return
	}

	cache := map[string]string{}
	changed := false
	for _, raw := range devices {
		bd, ok := raw.(map[string]any)
		if !ok {
			continue
		}
		if setImageName(ctx, d, meta, name, cache, bd) {
			changed = true
		}
	}

	if !changed {
		return
	}
	if err := d.Set(blockDeviceField, devices); err != nil {
		log.Printf("[DEBUG] cannot set block_device image names: %s", err)
	}
}

// setImageName fills image_name of a single image-backed block device and
// reports whether it was modified. Results are cached per image ID.
func setImageName(ctx context.Context, d *schema.ResourceData, meta any, name imageNamer, cache map[string]string, bd map[string]any) bool {
	uuid, _ := bd[uuidField].(string)
	if st, _ := bd[sourceTypeField].(string); st != sourceTypeImage || uuid == "" {
		return false
	}

	n, cached := cache[uuid]
	if !cached {
		var err error
		if n, err = name(ctx, d, meta, uuid); err != nil {
			log.Printf("[DEBUG] cannot resolve name of image %s: %s", uuid, err)
			n = ""
		}
		cache[uuid] = n
	}
	if n == "" {
		return false
	}
	bd[imageNameField] = n

	return true
}

func resolveImageNameByID(ctx context.Context, d *schema.ResourceData, meta any, id string) (string, error) {
	cfg, ok := meta.(*openstack.Config)
	if !ok {
		return "", errors.Errorf("unexpected provider meta type %T", meta)
	}
	client, err := cfg.ImageV2Client(ctx, openstack.GetRegion(d, cfg))
	if err != nil {
		return "", errors.Wrap(err, "cannot create OpenStack image client")
	}
	img, err := images.Get(ctx, client, id).Extract()
	if err != nil {
		return "", err
	}

	return img.Name, nil
}
